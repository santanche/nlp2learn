#!/usr/bin/env bash
# Creates (or updates) a local branch holding ONLY the Binder environment for
# techniques/ner: binder/requirements.txt, binder/runtime.txt, binder/postBuild.
#
# The notebooks are not on that branch: nbgitpuller pulls them from `main` when
# a session starts, so editing the notebooks never triggers an image rebuild.
# Re-run this script (and push) only when requirements.txt or postBuild change.
#
# Usage: techniques/ner/binder-env/make_branch.sh [branch-name]   (default: binder-ner)
# It commits locally only; push yourself with: git push -u origin binder-ner
set -euo pipefail

BRANCH="${1:-binder-ner}"
HERE="$(cd "$(dirname "$0")" && pwd)"
NER_DIR="$(dirname "$HERE")"
REPO="$(git -C "$HERE" rev-parse --show-toplevel)"
WT="$(mktemp -d)"
trap 'git -C "$REPO" worktree remove --force "$WT" 2>/dev/null || true' EXIT

if git -C "$REPO" show-ref --verify --quiet "refs/heads/$BRANCH"; then
  git -C "$REPO" worktree add --quiet "$WT" "$BRANCH"
else
  git -C "$REPO" worktree add --quiet --detach "$WT"
  git -C "$WT" checkout --quiet --orphan "$BRANCH"
  git -C "$WT" rm -rf --quiet .
fi

mkdir -p "$WT/binder"
cp "$NER_DIR/requirements.txt" "$WT/binder/requirements.txt"
cp "$HERE/runtime.txt" "$HERE/postBuild" "$WT/binder/"
chmod +x "$WT/binder/postBuild"
cat > "$WT/README.md" <<EOF
# Binder environment for \`techniques/ner\`

This branch only holds the Binder image definition (\`binder/\`). The notebooks
live on \`main\` and are pulled into each session by nbgitpuller.

Generated by \`techniques/ner/binder-env/make_branch.sh\` on \`main\` — edit the
files there, not here.
EOF

git -C "$WT" add -A
if git -C "$WT" diff --cached --quiet; then
  echo "Branch '$BRANCH' already up to date."
else
  git -C "$WT" commit --quiet -m "binder: environment for techniques/ner"
  echo "Committed to local branch '$BRANCH'. Publish it with:"
  echo "  git push -u origin $BRANCH"
fi
